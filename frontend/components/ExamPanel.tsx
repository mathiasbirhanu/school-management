"use client";

import { useState } from "react";
import { api, ApiError } from "@/lib/api";

type ExamPaper = { examId: string; topicId: string; topicTitle: string; questions: { id: string; prompt: string; maxScore: number }[] };
type Evaluation = {
  scorePercent: number;
  overallFeedback: string;
  results: { questionId: string; verdict: string; score: number; maxScore: number; feedback: string }[];
};

const verdictStyle: Record<string, string> = {
  correct: "bg-emerald-100 text-emerald-700",
  partial: "bg-gold-50 text-gold-dark",
  incorrect: "bg-rose-100 text-rose-600"
};

/**
 * AI practice test panel — every attempt is freshly generated by AI from the topic's
 * key concepts, graded by AI on submit, and stored NOWHERE (transient by design).
 */
export default function ExamPanel({ topicId, topicTitle }: { topicId: string; topicTitle: string }) {
  const [paper, setPaper] = useState<ExamPaper | null>(null);
  const [answers, setAnswers] = useState<Record<string, string>>({});
  const [evaluation, setEvaluation] = useState<Evaluation | null>(null);
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | null>(null);

  const generate = async () => {
    setBusy(true);
    setError(null);
    setEvaluation(null);
    setAnswers({});
    try {
      setPaper(await api<ExamPaper>("/api/ai-exam/generate", { method: "POST", body: { topicId } }));
    } catch (e) {
      setError(e instanceof ApiError ? e.message : "Could not generate the test.");
    } finally {
      setBusy(false);
    }
  };

  const submit = async () => {
    if (!paper) return;
    setBusy(true);
    setError(null);
    try {
      setEvaluation(
        await api<Evaluation>("/api/ai-exam/evaluate", {
          method: "POST",
          body: {
            examId: paper.examId,
            answers: paper.questions.map((q) => ({ questionId: q.id, text: answers[q.id] ?? "" }))
          }
        })
      );
    } catch (e) {
      setError(e instanceof ApiError ? e.message : "Could not evaluate your answers.");
    } finally {
      setBusy(false);
    }
  };

  return (
    <section className="rounded-2xl bg-white p-5 shadow-sm ring-1 ring-black/5">
      <div className="flex flex-wrap items-center justify-between gap-2">
        <h3 className="font-extrabold text-brand">AI practice test · {topicTitle}</h3>
        <span className="rounded-full bg-brand-50 px-2.5 py-1 text-[11px] font-semibold text-brand">
          Fresh every attempt · never saved
        </span>
      </div>
      <p className="mt-1 text-[13px] text-slate-500">
        Questions are generated by AI from this topic&apos;s key concepts and graded instantly when you
        submit. Each student — and each attempt — gets a different paper.
      </p>

      {error && (
        <p className="mt-3 rounded-lg bg-rose-50 px-3 py-2 text-sm text-rose-600">{error}</p>
      )}

      {!paper && (
        <button
          onClick={generate}
          disabled={busy}
          className="mt-4 rounded-full bg-brand px-5 py-2 text-sm font-bold text-white shadow transition hover:bg-brand-dark disabled:opacity-50"
        >
          {busy ? "Generating…" : "✨ Generate my test"}
        </button>
      )}

      {paper && (
        <div className="mt-4 space-y-4">
          {paper.questions.map((q, i) => {
            const result = evaluation?.results.find((r) => r.questionId === q.id);
            return (
              <div key={q.id} className="rounded-xl border border-black/5 bg-[#FAFAFE] p-4">
                <div className="flex items-start justify-between gap-3">
                  <p className="text-sm font-semibold text-ink">
                    <span className="mr-2 inline-flex h-5 w-5 items-center justify-center rounded-full bg-brand text-[11px] text-white">
                      {i + 1}
                    </span>
                    {q.prompt}
                  </p>
                  {result && (
                    <span className={`shrink-0 rounded-full px-2 py-0.5 text-[11px] font-bold capitalize ${verdictStyle[result.verdict] ?? "bg-slate-100 text-slate-600"}`}>
                      {result.verdict} · {result.score}/{result.maxScore}
                    </span>
                  )}
                </div>
                <textarea
                  rows={3}
                  value={answers[q.id] ?? ""}
                  onChange={(e) => setAnswers({ ...answers, [q.id]: e.target.value })}
                  disabled={!!evaluation}
                  placeholder="Write your answer in your own words (2-6 sentences)…"
                  className="mt-2 w-full resize-y rounded-lg border border-black/10 bg-white p-2.5 text-sm focus:border-brand focus:outline-none disabled:bg-slate-50"
                />
                {result && (
                  <p className="mt-2 text-[13px] leading-relaxed text-slate-600">
                    <span className="font-semibold text-brand">AI feedback: </span>
                    {result.feedback}
                  </p>
                )}
              </div>
            );
          })}

          {evaluation ? (
            <div className="rounded-xl bg-brand-50 p-4">
              <div className="flex items-center gap-4">
                <div className="relative h-16 w-16 shrink-0">
                  <svg viewBox="0 0 36 36" className="h-16 w-16 -rotate-90">
                    <circle cx="18" cy="18" r="15.9" fill="none" stroke="#D9DBF2" strokeWidth="4" />
                    <circle
                      cx="18"
                      cy="18"
                      r="15.9"
                      fill="none"
                      stroke="#3F3D8F"
                      strokeWidth="4"
                      strokeDasharray={`${(evaluation.scorePercent / 100) * 100} 100`}
                      strokeLinecap="round"
                    />
                  </svg>
                  <span className="absolute inset-0 flex items-center justify-center text-sm font-extrabold text-brand">
                    {Math.round(evaluation.scorePercent)}%
                  </span>
                </div>
                <div>
                  <p className="text-sm font-bold text-brand">Attempt graded by AI</p>
                  <p className="text-[13px] text-slate-600">{evaluation.overallFeedback}</p>
                  <p className="mt-1 text-[11px] text-slate-400">
                    This attempt was not saved anywhere — only you saw it.
                  </p>
                </div>
              </div>
              <button
                onClick={generate}
                disabled={busy}
                className="mt-3 rounded-full bg-gold px-4 py-1.5 text-sm font-bold text-white shadow hover:bg-gold-dark disabled:opacity-50"
              >
                {busy ? "Generating…" : "Try a fresh test"}
              </button>
            </div>
          ) : (
            <div className="flex gap-3">
              <button
                onClick={submit}
                disabled={busy}
                className="rounded-full bg-gold px-5 py-2 text-sm font-bold text-white shadow hover:bg-gold-dark disabled:opacity-50"
              >
                {busy ? "AI is grading…" : "Submit for AI grading"}
              </button>
              <button onClick={generate} disabled={busy} className="text-sm font-semibold text-slate-500 hover:text-brand">
                Regenerate
              </button>
            </div>
          )}
        </div>
      )}
    </section>
  );
}
